import React, { useState } from 'react';
import { X, Send, FileCheck, ShieldCheck } from 'lucide-react';
import type { CuratedEvent } from '../data/auctionData';

interface ConditionReportModalProps {
  event: CuratedEvent | null;
  onClose: () => void;
  onSubmitReport: (email: string, notes: string) => void;
}

export const ConditionReportModal: React.FC<ConditionReportModalProps> = ({
  event,
  onClose,
  onSubmitReport
}) => {
  if (!event) return null;

  const [email, setEmail] = useState('');
  const [paddleNumber, setPaddleNumber] = useState('');
  const [notes, setNotes] = useState('');
  const [submitted, setSubmitted] = useState(false);

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (!email) return;

    setSubmitted(true);
    setTimeout(() => {
      onSubmitReport(email, notes);
      setSubmitted(false);
      onClose();
    }, 1000);
  };

  return (
    <div className="modal-backdrop" onClick={onClose}>
      <div className="modal-card condition-modal" onClick={(e) => e.stopPropagation()}>
        <div className="modal-header">
          <div className="modal-header-titles">
            <span className="modal-tag">SPECIALIST CONNOISSEUR DESK</span>
            <h3 className="modal-title">Request Official Condition Dossier</h3>
          </div>
          <button className="modal-close-btn" onClick={onClose}>
            <X size={20} />
          </button>
        </div>

        <form onSubmit={handleSubmit} className="modal-body">
          <p className="condition-intro">
            Request an authenticated, high-resolution condition report for lots in{' '}
            <strong>{event.title}</strong> compiled by our accredited appraisers.
          </p>

          <div className="form-group">
            <label className="form-label">Bidder Email Address *</label>
            <input
              type="email"
              required
              className="form-input"
              placeholder="collector@example.com"
              value={email}
              onChange={(e) => setEmail(e.target.value)}
            />
          </div>

          <div className="form-group">
            <label className="form-label">Registered Paddle / Bidder ID (Optional)</label>
            <input
              type="text"
              className="form-input"
              placeholder="e.g. PA-4820"
              value={paddleNumber}
              onChange={(e) => setPaddleNumber(e.target.value)}
            />
          </div>

          <div className="form-group">
            <label className="form-label">Specific Lots of Interest or Questions</label>
            <textarea
              className="form-textarea"
              rows={3}
              placeholder="Inquire regarding UV inspection, frame restoration history, or high-res microscopic details..."
              value={notes}
              onChange={(e) => setNotes(e.target.value)}
            />
          </div>

          <div className="modal-actions">
            <button type="submit" className="btn-confirm-bid" disabled={submitted}>
              {submitted ? (
                <>
                  <FileCheck size={18} />
                  <span>Dossier Dispatched!</span>
                </>
              ) : (
                <>
                  <Send size={18} />
                  <span>DISPATCH CONDITION DOSSIER</span>
                </>
              )}
            </button>
          </div>

          <div className="bid-security-notice">
            <ShieldCheck size={14} className="gold-icon" />
            <span>Reports generated by members of the Appraisers Association of America (AAA)</span>
          </div>
        </form>
      </div>
    </div>
  );
};
